const add = (...num) => {
  const result = num.reduce((acc, currentValue) => acc + currentValue);
  return result;
};

const subtract = (...num) => {
  const result = num.reduce((acc, currentValue) => acc - currentValue);
  return result;
};

const multiply = (...num) => {
  const result = num.reduce((acc, currentValue) => acc * currentValue);
  return result;
};

const divide = (...num) => {
  const result = num.reduce((acc, currentValue) => acc * currentValue);
  return result;
};
